# Logs

RE_PAIR = re.compile(r"(\d+)x\(VS=([0-9A-F]{16}),PS=([0-9A-F]{16})\)")
RE_UNIDENT = re.compile(r"unidentified (pixel|vertex) shader: (\d+) words, fingerprint ([0-9A-F]{16})")
RE_MISSING_DRAW = re.compile(r"missing shader draw: VS ([0-9A-F]{16}) (found|MISSING).*?PS ([0-9A-F]{16}) (found|MISSING)")
RE_MICRO = re.compile(r"missing shader microcode (VS|PS) ([0-9A-F]{16}) (\d+) words \[(\d+)\]:((?: [0-9A-F]{8})+)")


class Seen:
    def __init__(self, vertex, h):
        self.vertex = vertex
        self.hash = h
        self.words = None
        self.logs = set()
        self.draws = 0          # max cumulative 'unresolved draw shader pairs' count of one log
        self.microcode = {}     # index -> word (from 'missing shader microcode')


def scan_logs(paths):
    seen = {}

    def get(vertex, h):
        key = (vertex, int(h, 16))
        if key not in seen:
            seen[key] = Seen(vertex, key[1])
        return seen[key]

    files = []
    for p in paths:
        if os.path.isdir(p):
            for root, _, names in os.walk(p):
                files += [os.path.join(root, n) for n in names if n.endswith((".log", ".txt"))]
        elif os.path.exists(p):
            files.append(p)
    for path in sorted(files):
        try:
            text = open(path, "r", errors="replace").read()
        except OSError:
            continue
        if "shader" not in text:
            continue
        per_log = {}
        for line in text.splitlines():
            if "unresolved draw shader pairs" in line:
                for count, vs, ps in RE_PAIR.findall(line):
                    # VS=0 means the VS was identified and the PS is missing, and the reverse.
                    if ps != "0" * 16 and vs == "0" * 16:
                        k = (False, ps)
                    elif vs != "0" * 16 and ps == "0" * 16:
                        k = (True, vs)
                    else:
                        for kk in ((True, vs), (False, ps)):
                            if kk[1] != "0" * 16:
                                per_log[kk] = max(per_log.get(kk, 0), int(count))
                        continue
                    per_log[k] = max(per_log.get(k, 0), int(count))
                continue
            m = RE_UNIDENT.search(line)
            if m:
                s = get(m.group(1) == "vertex", m.group(3))
                s.words = int(m.group(2))
                s.logs.add(path)
                continue
            m = RE_MISSING_DRAW.search(line)
            if m:
                if m.group(2) == "MISSING":
                    get(True, m.group(1)).logs.add(path)
                if m.group(4) == "MISSING":
                    get(False, m.group(3)).logs.add(path)
                continue
            m = RE_MICRO.search(line)
            if m:
                s = get(m.group(1) == "VS", m.group(2))
                s.words = int(m.group(3))
                first = int(m.group(4))
                for i, w in enumerate(m.group(5).split()):
                    s.microcode[first + i] = int(w, 16)
                s.logs.add(path)
        for (vertex, h), count in per_log.items():
            s = get(vertex, h)
            s.logs.add(path)
            s.draws = max(s.draws, count)
    for s in seen.values():
        if s.words and len(s.microcode) == s.words:
            words = [s.microcode[i] for i in range(s.words)]
            if xxh3(struct.pack("<%dI" % s.words, *words)) != s.hash:
                s.microcode = {}  # incomplete or mixed dump
        else:
            s.microcode = {}
    return seen


def read_prewarm(path):
    data = open(path, "rb").read()
    magic, version, size, count = struct.unpack_from("<IIII", data, 0)
    if magic != NFPL or len(data) != PREWARM_HEADER + size * count:
        raise SystemExit(f"{path}: not a prewarm list")
    fps = set()
    for i in range(count):
        r = PREWARM_HEADER + i * size
        ps_number = struct.unpack_from("<I", data, r + 4)[0]
        vs_fp, ps_fp = struct.unpack_from("<QQ", data, r + PREWARM_FP_OFFSET)
        if vs_fp:
            fps.add((True, vs_fp))
        if ps_number and ps_fp:
            fps.add((False, ps_fp))
    return fps


# ---------------------------------------------------------------------------------------------------------------

def stage(vertex):
    return "VS" if vertex else "PS"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("package")
    ap.add_argument("--reference", action="append", default=[])
    ap.add_argument("--containers", default=os.path.join(REPO, "shaders", "runtime_containers"))
    ap.add_argument("--containers-json", default=os.path.join(REPO, "installer", "wasm", "runtime_containers.json"))
    ap.add_argument("--logs", action="append", default=[])
    ap.add_argument("--prewarm", action="append", default=[])
    ap.add_argument("--json", help="write the findings as JSON")
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args()

    target = Package(a.package)
    containers = Package(a.containers) if a.containers and os.path.isdir(a.containers) else None
    bundled = load_containers_json(a.containers_json) if a.containers_json and os.path.exists(a.containers_json) else {}
    refs = [Package(p) for p in a.reference]
    findings = {"package": a.package, "entries": len(target.entries), "ignored_by_runtime": [],
                "runtime_containers_missing": [], "folder_vs_json": [], "reference_table_less_missing": [],
                "reference_other_missing": 0, "logged_missing": [], "prewarm_missing": []}
    bad = 0

    def where(vertex, h):
        out = []
        if containers and containers.has_code(vertex, h):
            out.append("runtime_containers/" + ",".join(str(e.number) for e in containers.by_code[(vertex, h)]))
        if any(e.code_hash == h and e.vertex == vertex for e in bundled.values()):
            out.append("installer-json")
        for r in refs:
            for e in r.by_code.get((vertex, h), [])[:1]:
                out.append(f"{os.path.basename(os.path.dirname(r.path)) or r.path}#{e.number}"
                           f"({'table-less' if e.table_less else 'CTAB'})")
        return out

    print(f"package {a.package}: {len(target.entries)} containers, "
          f"{sum(1 for e in target.entries if not e.problem)} usable by the runtime, "
          f"{len(target.by_code)} distinct (stage, microcode)")

    # 1. Containers the runtime ignores (masseffect_native_shaders.cpp Read()).
    for e in target.entries:
        if e.problem:  # harmless (the runtime skips it with a warning), not fatal: scanner false positives
            findings["ignored_by_runtime"].append({"number": e.number, "fingerprint": f"{e.fingerprint:016X}",
                                                   "reason": e.problem})
            print(f"IGNORED  container {e.number} ({e.fingerprint:016X}): {e.problem}")

    # 2. shaders/runtime_containers and the installer's JSON: every one must be in the package, and both must agree.
    if containers:
        for e in containers.entries:
            if e.problem:
                bad += 1
                print(f"BROKEN   runtime container {e.number}: {e.problem}")
            elif not target.has_code(e.vertex, e.code_hash):
                bad += 1
                findings["runtime_containers_missing"].append(e.number)
                print(f"MISSING  runtime container {e.number} ({stage(e.vertex)} {e.code_hash:016X}, {e.words} words)")
        names = {e.number for e in containers.entries}
        for n in sorted(names ^ set(bundled)):
            bad += 1
            side = "folder only" if n in names else "installer JSON only"
            findings["folder_vs_json"].append({"name": n, "side": side})
            print(f"DIFFERS  {n}: {side} (regenerate installer/wasm/runtime_containers.json)")
        for n in sorted(names & set(bundled)):
            c = next(e for e in containers.entries if e.number == n)
            if c.fingerprint != bundled[n].fingerprint:
                bad += 1
                findings["folder_vs_json"].append({"name": n, "side": "content differs"})
                print(f"DIFFERS  {n}: folder and installer JSON contents differ")

    # 3. Reference packages: table-less shaders missing from the package and from runtime_containers.
    for r in refs:
        missing_tl, other = [], 0
        for (vertex, h), es in r.by_code.items():
            if target.has_code(vertex, h):
                continue
            e = es[0]
            if e.table_less:
                in_rc = containers.has_code(vertex, h) if containers else False
                missing_tl.append((e, in_rc))
            else:
                other += 1
        findings["reference_other_missing"] += other
        print(f"reference {r.path}: {len(r.entries)} containers; missing from the package: {len(missing_tl)} "
              f"table-less (runtime) shaders, {other} CTAB (disc package) shaders")
        for e, in_rc in sorted(missing_tl, key=lambda t: (t[0].vertex, t[0].words)):
            bad += 1
            findings["reference_table_less_missing"].append({
                "reference": r.path, "stage": stage(e.vertex), "hash": f"{e.code_hash:016X}", "words": e.words,
                "container": f"{e.fingerprint:016X}", "in_runtime_containers": in_rc})
            print(f"MISSING  table-less {stage(e.vertex)} {e.code_hash:016X} ({e.words} words, container "
                  f"{e.fingerprint:016X}, ref #{e.number}){' [in runtime_containers]' if in_rc else ''}")

    # 4. Hashes the console reported.
    if a.logs:
        seen = scan_logs(a.logs)
        rows = []
        for (vertex, h), s in seen.items():
            if target.has_code(vertex, h):
                continue
            if vertex and s.microcode and target.identify_vs([s.microcode[i] for i in range(s.words)]):
                continue  # a fetch-patched variant of a package VS
            rows.append(s)
        rows.sort(key=lambda s: (-s.draws, s.vertex, s.hash))
        print(f"logs: {len(seen)} distinct shader hashes reported, {len(rows)} not in the package "
              "(by unpatched microcode hash)")
        for s in rows:
            w = where(s.vertex, s.hash)
            kind = ("runtime" if any("table-less" in x or x.startswith(("runtime_containers", "installer"))
                                     for x in w) else "disc" if any("CTAB" in x for x in w) else "unknown")
            if s.vertex and not w:
                # Direct3D patches VS fetches, so a logged VS hash is not proof: the runtime's second (patched-fetch)
                # lookup may still find it. Reported, not fatal; a later log with the same package decides.
                kind = "VS (not proven missing: patched at run time)" + ("" if s.microcode else ", no microcode dump")
            else:
                bad += 1
            findings["logged_missing"].append({
                "stage": stage(s.vertex), "hash": f"{s.hash:016X}", "words": s.words, "max_draws": s.draws,
                "logs": len(s.logs), "kind": kind, "found_in": w, "microcode_in_log": bool(s.microcode),
                "example_log": sorted(s.logs)[-1] if s.logs else None})
            print(f"LOGGED   {stage(s.vertex)} {s.hash:016X} words={s.words} max_draws={s.draws} logs={len(s.logs)} "
                  f"kind={kind} found_in={','.join(w) or '-'}{' microcode-in-log' if s.microcode else ''}")
            if a.verbose:
                for p in sorted(s.logs)[-3:]:
                    print(f"           {p}")

    # 5. Prewarm lists (container fingerprints).
    for p in a.prewarm:
        fps = read_prewarm(p)
        miss = [(v, fp) for v, fp in fps if fp not in target.by_fp]
        print(f"prewarm {p}: {len(fps)} distinct shaders, {len(miss)} not in the package")
        for v, fp in sorted(miss):
            findings["prewarm_missing"].append({"list": p, "stage": stage(v), "container": f"{fp:016X}"})
            if a.verbose:
                print(f"PREWARM  {stage(v)} container {fp:016X} not in the package")
        # A list recorded against another package only loses pipelines (a cold-start hitch), not draws.

    if a.json:
        with open(a.json, "w") as f:
            json.dump(findings, f, indent=1)
    print("RESULT: " + ("problems found" if bad else "ok"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
