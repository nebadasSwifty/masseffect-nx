#!/usr/bin/env python3
"""Offline shader coverage check of a shader package (.mesp / .mesp.idx) before a release.

Answers "which shaders that the game is known to use are NOT in this package, and where do they come from".

usage:
  tools/check_shader_coverage.py PACKAGE [--reference PKG ...] [--containers DIR] [--containers-json JSON]
                                 [--logs PATH ...] [--prewarm LIST.bin ...] [--json OUT.json] [-v]

PACKAGE / PKG   a masseffect_shaders.mesp or its .mesp.idx (the index is read when it exists: fast, no SPIR-V).
                Also accepted: a folder of *.bin containers (shaders/runtime_containers layout).
--reference     other packages (older console packages, the other edition, v27 lineage, ...). Every TABLE-LESS
                shader (Direct3D / Scaleform runtime shader: no CTAB or a CTAB with 0 constants) in a reference that
                is missing from PACKAGE and from --containers is reported: those are generated by default.xex at run
                time, so no disc scan can ever find them again; they only survive through shaders/runtime_containers.
--containers    shaders/runtime_containers (default: <repo>/shaders/runtime_containers when it exists).
--containers-json  installer/wasm/runtime_containers.json (what the public web installer bundles). Default: the repo's.
--logs          console logs or folders of logs (searched recursively for *.log / *.txt). Hashes are collected
                from 'unresolved draw shader pairs', 'unidentified pixel|vertex shader', 'missing shader draw' and
                'missing shader microcode' lines; complete microcode dumps are reassembled.
--prewarm       pipeline prewarm lists (NFPL, app/prewarm/*.bin): their records name shaders by container
                fingerprint.

Identities (they must match the runtime exactly):
  * microcode hash ("host hash", the PS=/VS= values of the logs) = XXH3-64 over the microcode words in host order
    (me_native_system.cpp CodeHash, masseffect_native_shaders.cpp Read: e.fingerprint for pixel shaders);
    the microcode is at virtual_size + shader_header.offset, shader_header.size bytes (2008 layout 0x102A11xx).
  * container fingerprint (prewarm lists, the .idx) = XXH3-64 of the whole original container.
  Vertex shaders arrive patched by Direct3D (fetch swizzles), so a VS hash of a log only matches a package VS when
  the shader was not patched; VS from logs are reported separately and are only proven missing with a microcode dump.

Exit code: 0 nothing missing, 1 something missing (containers the runtime ignores are listed as IGNORED, not fatal).
Needs the Python package 'xxhash' (python3 -m pip install xxhash).
"""
import argparse
import base64
import json
import os
import re
import struct
import sys

try:
    import xxhash
except ImportError:  # pragma: no cover
    sys.exit("error: the Python package 'xxhash' is required (python3 -m pip install xxhash)")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NFPL = 0x4C50464E
PREWARM_HEADER = 16
PREWARM_FP_OFFSET = 104  # sizeof(PipelineKey): u64 vs_fingerprint, u64 ps_fingerprint follow


def be32(b, o):
    return struct.unpack_from(">I", b, o)[0]


def xxh3(b):
    return xxhash.xxh3_64_intdigest(b)


FETCH_KEEPS = (0x0007FFFF, 0x80000FFF, 0x80000000)  # masseffect_native_shaders.cpp kFetchKeeps


def fetches_of_vertices(w):
    """masseffect_native_shaders.cpp FetchesOfVertices: (instruction, destination register) of every vertex fetch."""
    out = []
    end = len(w) // 3
    par = 0
    while par < end and par * 3 + 2 < len(w):
        cf = (w[par * 3] | ((w[par * 3 + 1] & 0xFFFF) << 32), (w[par * 3 + 1] >> 16) | (w[par * 3 + 2] << 16))
        for c in cf:
            op = (c >> 44) & 0xF
            if not (1 <= op <= 6 or op in (13, 14)):
                continue
            address, count, seq = c & 0xFFF, (c >> 12) & 0x7, (c >> 16) & 0xFFF
            if address:
                end = min(end, address)
            for i in range(count):
                index = address + i
                if not (seq >> (i * 2)) & 1 or index * 3 + 2 >= len(w):
                    continue
                if w[index * 3] & 0x1F:
                    continue
                out.append((index, (w[index * 3] >> 12) & 0x3F))
        par += 1
    return out


def mask_fetches(words, instructions):
    w = list(words)
    for ins in instructions:
        for j in range(3):
            if ins * 3 + j < len(w):
                w[ins * 3 + j] &= FETCH_KEEPS[j]
    return w


class Entry:
    __slots__ = ("number", "fingerprint", "vertex", "words", "code_hash", "table_less", "problem", "microcode",
                 "elements", "masked")

    def __init__(self, number, original):
        self.number = number
        self.fingerprint = xxh3(original)
        self.vertex = bool(be32(original, 0) & 1) if len(original) >= 4 else False
        self.words = 0
        self.code_hash = None
        self.table_less = False
        self.problem = None
        self.microcode = None
        self.elements = []   # VS: fetch instructions the runtime masks (identity = masked microcode)
        self.masked = None
        self._read(original)

    def _read(self, o):
        """The checks of masseffect_native_shaders.cpp Read() that make the runtime ignore a container."""
        n = len(o)
        if n < 28:
            self.problem = "container too short"
            return
        sig = be32(o, 0)
        if (sig & 0xFFFFFF00) != 0x102A1100:
            self.problem = "not a 2008 (0x102A11xx) container"
            return
        virtual = be32(o, 4)
        table = be32(o, 16)
        header = be32(o, 24)
        self.table_less = (not table) or (table + 20 <= n and be32(o, table + 16) == 0)
        if header + 8 > n:
            self.problem = "shader header outside the container"
            return
        offset, size = be32(o, header), be32(o, header + 4)
        start = virtual + offset
        if not size or size % 4 or start + size > n:
            self.problem = "microcode outside the container"
            return
        if header >= virtual or header + (40 if self.vertex else 32) > virtual:
            self.problem = "shader header outside the virtual part"
            return
        words = struct.unpack_from(">%dI" % (size // 4), o, start)
        self.words = len(words)
        self.microcode = words
        self.code_hash = xxh3(struct.pack("<%dI" % len(words), *words))
        if self.vertex:
            previous, count = be32(o, header + 24), be32(o, header + 28)
            begin = header + 36 + previous * 4
            if count > 64 or previous > 1024 or begin + count * 4 > virtual:
                self.problem = "vertex elements outside the virtual part"
                return
            if self.table_less:
                self.elements = [i for i, _ in fetches_of_vertices(words)]
            else:
                self.elements = [be32(o, begin + 4 * i) & 0xFFF for i in range(count)]
            self.masked = tuple(mask_fetches(words, self.elements))


class Package:
    def __init__(self, path):
        self.path = path
        self.entries = []
        if os.path.isdir(path):
            for name in sorted(os.listdir(path)):
                if name.endswith(".bin"):
                    with open(os.path.join(path, name), "rb") as f:
                        e = Entry(name, f.read())
                    self.entries.append(e)
        else:
            idx = path if path.endswith(".idx") else path + ".idx"
            if os.path.exists(idx):
                self._load_idx(idx)
            else:
                self._load_mesp(path)
        self.by_code = {}
        self.by_fp = {}
        self.vs_by_words = {}
        for e in self.entries:
            self.by_fp.setdefault(e.fingerprint, e)
            if e.code_hash is not None:
                self.by_code.setdefault((e.vertex, e.code_hash), []).append(e)
                if e.vertex and e.masked is not None:
                    self.vs_by_words.setdefault(e.words, []).append(e)

    def _load_idx(self, idx):
        data = open(idx, "rb").read()
        if data[:8] != b"MESSIDX\0":
            raise SystemExit(f"{idx}: not a shader package index")
        count = struct.unpack_from("<I", data, 12)[0]
        package_size = struct.unpack_from("<Q", data, 16)[0]
        mesp = idx[:-4]
        if os.path.exists(mesp) and os.path.getsize(mesp) != package_size:
            print(f"warning: {idx} belongs to a package of {package_size} bytes, {mesp} has "
                  f"{os.path.getsize(mesp)}: the runtime will not use this index", file=sys.stderr)
        pos = 56 + count * 40
        for i in range(count):
            original = struct.unpack_from("<I", data, 56 + i * 40)[0]
            stored = struct.unpack_from("<Q", data, 56 + i * 40 + 8)[0]
            e = Entry(i, data[pos:pos + original])
            if e.fingerprint != stored:
                e.problem = "container fingerprint differs from the index"
            self.entries.append(e)
            pos += original

    def _load_mesp(self, path):
        with open(path, "rb") as f:
            head = f.read(24)
            if head[:8] not in (b"MESSPV\0\0", b"NFSSPV\0\0"):  # NFSSPV: the older (v27) lineage, same layout
                raise SystemExit(f"{path}: not a shader package")
            count = struct.unpack_from("<I", head, 12)[0]
            for i in range(count):
                original, words = struct.unpack_from("<II", f.read(16), 0)
                e = Entry(i, f.read(original))
                f.seek(words * 4, os.SEEK_CUR)
                self.entries.append(e)

    def has_code(self, vertex, code_hash):
        return (vertex, code_hash) in self.by_code

    def identify_vs(self, words):
        """First stage of ShadersNative::Identify for a (possibly patched) VS microcode: mask the fetches of each
        same-length candidate and compare. Returns the entry or None (the runtime's second, permissive stage is
        not modelled, so None means 'not proven present')."""
        for e in self.vs_by_words.get(len(words), []):
            if tuple(mask_fetches(words, e.elements)) == e.masked:
                return e
        return None


def load_containers_json(path):
    out = {}
    for name, b64 in json.load(open(path)).items():
        out[name] = Entry(name, base64.b64decode(b64))
    return out


